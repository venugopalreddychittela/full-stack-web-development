// Q6: Node.js Modules Demonstration
// Demonstrating built-in modules: os, path, and fs

// Importing the required Node.js built-in modules
const os = require("os");
const path = require("path");
const fs = require("fs");


// ==================================================
// PART 1: OS MODULE
// ==================================================

// The os module provides information about the
// operating system and computer hardware.

console.log("========== OS MODULE ==========");

console.log("Operating System:", os.platform());
console.log("OS Type:", os.type());
console.log("CPU Architecture:", os.arch());
console.log("Number of CPU Cores:", os.cpus().length);
console.log("Total Memory:", (os.totalmem() / (1024 ** 3)).toFixed(2), "GB");
console.log("Free Memory:", (os.freemem() / (1024 ** 3)).toFixed(2), "GB");
console.log("Home Directory:", os.homedir());


// ==================================================
// PART 2: PATH MODULE
// ==================================================

// The path module is used for working with
// file and directory paths.

console.log("\n========== PATH MODULE ==========");

const folder = "documents";
const fileName = "student.txt";

// Joining folder and file name into one path
const fullPath = path.join(folder, fileName);

console.log("Folder:", folder);
console.log("File Name:", fileName);
console.log("Complete Path:", fullPath);

// Extracting different parts of the path
console.log("Directory Name:", path.dirname(fullPath));
console.log("File Name:", path.basename(fullPath));
console.log("File Extension:", path.extname(fullPath));


// ==================================================
// PART 3: FS MODULE
// ==================================================

// The fs (File System) module is used to
// create, write, read, and modify files.

console.log("\n========== FS MODULE ==========");

const filePath = path.join(__dirname, "student_data.txt");

// Data to be written into the file
const initialData =
    "Name: Venu\n" +
    "Roll Number: A24126552078\n" +
    "Branch: CSM\n";

// Creating and writing data to the file
fs.writeFileSync(filePath, initialData);

console.log("File created and data written successfully.");


// Reading the file
const fileData = fs.readFileSync(filePath, "utf8");

console.log("\nData read from file:");
console.log(fileData);


// Appending additional information
const additionalData = "College: ANITS\n";

fs.appendFileSync(filePath, additionalData);

console.log("Additional data appended successfully.");


// Reading the updated file
const updatedData = fs.readFileSync(filePath, "utf8");

console.log("\nUpdated file content:");
console.log(updatedData);


// Checking whether the file exists
if (fs.existsSync(filePath)) {
    console.log("File exists:", filePath);
}


// ==================================================
// FINAL MESSAGE
// ==================================================

console.log("\n========== PROGRAM COMPLETED ==========");
console.log("OS, Path and FS modules demonstrated successfully.");